"""Crop and split MediaPipe capture sessions for gesture classification."""
import argparse
import hashlib
import json
from collections import Counter
from datetime import datetime
from pathlib import Path

from PIL import Image

CLASSES = ('like', 'ok', 'open_palm')


def prepare(raw: Path, output: Path) -> dict:
    if output.exists():
        raise ValueError(f'{output} already exists; remove it or choose another output directory.')
    entries = {label: [] for label in CLASSES}
    errors = []
    for label in CLASSES:
        for image_path in sorted((raw / label).glob('*.jpg')):
            annotation_path = image_path.with_suffix('.json')
            try:
                annotation = json.loads(annotation_path.read_text())
                if annotation.get('label') != label or len(annotation.get('landmarks', [])) != 21:
                    raise ValueError('class label or landmark count mismatch')
                stamp = datetime.fromisoformat(annotation['captured_at'].replace('Z', '+00:00'))
                with Image.open(image_path) as source:
                    source.load()
                    width, height = source.size
                    box = annotation['bbox']
                    x0 = max(0, int(box['x'] * width))
                    y0 = max(0, int(box['y'] * height))
                    x1 = min(width, int((box['x'] + box['width']) * width + .999))
                    y1 = min(height, int((box['y'] + box['height']) * height + .999))
                    if x1 <= x0 or y1 <= y0:
                        raise ValueError('empty hand bounding box')
                    crop = source.convert('RGB').crop((x0, y0, x1, y1))
                    entries[label].append((stamp, image_path, annotation_path, crop))
            except Exception as exc:
                errors.append({'image': str(image_path), 'error': str(exc)})
    if errors:
        raise ValueError(f'{len(errors)} invalid image/annotation pairs; first: {errors[0]}')
    if any(len(rows) < 20 for rows in entries.values()):
        raise ValueError('Each of the three classes needs at least 20 valid captures.')

    rows_out, distribution = [], {s: Counter() for s in ('train', 'val', 'test')}
    # Captures are time-correlated. Keep each class in chronological blocks so
    # adjacent near-identical frames cannot land on opposite sides of a split.
    for label, rows in entries.items():
        rows.sort(key=lambda row: (row[0], row[1].name))
        n = len(rows)
        cut_train, cut_val = int(n * .70), int(n * .85)
        for i, (stamp, image_path, annotation_path, crop) in enumerate(rows):
            split = 'train' if i < cut_train else 'val' if i < cut_val else 'test'
            target = output / split / label / f'{image_path.stem}.jpg'
            target.parent.mkdir(parents=True, exist_ok=True)
            crop.save(target, quality=95)
            digest = hashlib.sha256(target.read_bytes()).hexdigest()
            rows_out.append({'source': str(image_path), 'annotation': str(annotation_path),
                             'processed': str(target), 'sha256': digest, 'label': label,
                             'split': split, 'capture_session': label, 'captured_at': stamp.isoformat()})
            distribution[split][label] += 1
    manifest = {'format': 'image-level classification', 'classes': list(CLASSES),
                'class_mapping': {str(i): label for i, label in enumerate(CLASSES)},
                'source': str(raw), 'split_method': 'chronological 70/15/15 per gesture capture session',
                'splits': {split: dict(counts) for split, counts in distribution.items()},
                'manifest': rows_out,
                'limitations': ['Each gesture was captured in one continuous session; time splits reduce adjacent-frame leakage but do not test a new person, session, camera, or background.',
                                'Gesture labels are generated by landmark heuristics and should be reviewed, especially OK and thumbs up.',
                                'No negative gestures or empty-scene captures are included.']}
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2))
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raw', type=Path, default=Path('data/dataset_creator'))
    parser.add_argument('--output', type=Path, default=Path('data/gesture_captures'))
    args = parser.parse_args()
    result = prepare(args.raw, args.output)
    print(json.dumps(result['splits'], indent=2))


if __name__ == '__main__':
    main()
